fn recovered(points: &[[u64; 3]]) -> solidfem_tetra::RecoveryReport {
    let points: Vec<[f64; 3]> = points.iter().map(|p| p.map(f64::from_bits)).collect();
    let triangles = prism(40, 5.0, 2.0, false).triangles;
    let (solid, report) = mesh(&points, &triangles).unwrap_or_else(|error| panic!("{error}"));
    assert_solid(&solid, &points, &triangles);
    report
}

/// A relief flip made while removing a blocking edge can happen to create the very edge being
/// recovered. That edge's vertex then looks, wrongly, like a vertex lying on the edge.
#[test]
fn an_edge_made_by_a_neighbouring_flip_counts_as_recovered() {
    recovered(&FAN_PRISM_7);
}

/// A side quad's diagonal runs just inside the hull where rounding folded the quad outward along
/// the other diagonal. No flip can remove a hull edge that is not flat, so the recovery needs the
/// flip that keeps the fold with a sliver under it.
#[test]
fn a_surface_edge_under_a_fold_of_the_hull_is_recovered() {
    recovered(&FAN_PRISM_12);
}

/// Here the same fold has a shorter ring, and the flip that keeps it with a sliver finishes the
/// edge with no point added at all.
#[test]
fn a_fold_of_the_hull_can_be_closed_by_a_flip_alone() {
    assert_eq!(
        recovered(&FAN_PRISM_89).steiner_points,
        0,
        "the fold flip alone finishes this edge"
    );
}
