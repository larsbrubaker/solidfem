//! The example parts the page offers beyond the bar and tube: the real-part benchmarks, each named
//! for a visitor, with one line of what it tests, where it is held and loaded, and an honest
//! status line from the benchmark's verdict.
//!
//! **The status strings live here, in one table.** When a verdict changes (rerun
//! `solidfem-benchmarks` on the output of `solidfem-surfaces`, or read the verdict the case prints),
//! update [`EXAMPLES`]: `verdict` and `status` must only say what the benchmark showed. A failing
//! part says so first; a pass limited to mesh stability or a nominal value says what it did not
//! test.
//!
//! The surface of each entry is a file under `demo/public/parts/`, generated by `solidfem-surfaces`
//! and named by its benchmark density, so the mesher, holds, loads and material here are the
//! benchmark's own (`cases`). The page solves that one density, coarser than the finest the
//! benchmark judged, so its numbers can differ from the verdict's: the status says what the
//! benchmark found, and the page's own mesh is only ever described as a preview of it.
//!
//! Every part solves with multigrid: `tests/demo/parts_timing.rs` measures that the slender ones
//! would take tens of thousands of Jacobi iterations and the compact ones are still several times
//! faster with it.
//!
//! Three surfaces are no benchmark density (`demo_sizing`), because a browser has to solve them in
//! a wait a visitor will sit through. The benchmark's verdict does not cover those meshes, so
//! their status lines quote what the page's own mesh measured, and `tests/demo/parts.rs` holds
//! each quoted figure to a real solve of that mesh.

use solidfem::elastic::Material;
use solidfem_bench::benchmarks::cases::{all_cases, Case, Density, Sizing, LOAD_DISK};

/// How the benchmark judged a part, for the page's styling.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Verdict {
    /// Within its limits against a published or closed-form answer.
    Pass,
    /// Within its limits, but those limits do not include an accuracy reference.
    Limited,
    /// A limit was broken or a stage refused the part.
    Fail,
}

impl Verdict {
    /// The name the page's styling keys on.
    pub fn name(self) -> &'static str {
        match self {
            Verdict::Pass => "pass",
            Verdict::Limited => "limited",
            Verdict::Fail => "fail",
        }
    }
}

/// One example part: everything the page shows and the benchmark entry behind it.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ExamplePart {
    /// The name the page picks it by.
    pub id: &'static str,
    /// The benchmark case it runs.
    pub case_id: &'static str,
    /// The surface file, which is also the asset's name under `demo/public/parts/`. Either one
    /// of the case's densities, or a demo-only surface (see `demo_sizing`).
    pub surface_file: &'static str,
    /// Set for a surface that is no benchmark density: its size function, coarser than the
    /// benchmark's because a browser must solve it. `status` then says what that costs.
    pub demo_sizing: Option<Sizing>,
    /// Elements through a thin wall when this part differs from its case, for a demo-only mesh
    /// whose load does not bend the wall, so one layer of 10-node elements carries it.
    pub demo_layers: Option<u32>,
    /// From the part towards the camera on opening, chosen to show the part's shape: along its
    /// thin direction with some tilt where the outline is what matters, and from the side where
    /// the bending is.
    pub view: [f64; 3],
    /// The disk the load acts on, when it is smaller than the faces it touches: (centre in x and
    /// y, radius). Its arrows are drawn inside the disk, because a face only partly under the
    /// load carries a part of it.
    pub load_disk: Option<([f64; 2], f64)>,
    pub name: &'static str,
    /// One line of what the part tests, in plain words.
    pub tests: &'static str,
    /// Where it is held, in plain words.
    pub held: &'static str,
    /// Where and how it is loaded, in plain words.
    pub loaded: &'static str,
    /// The benchmark's load as the page's load-size slider describes it at 1x.
    pub load: &'static str,
    pub verdict: Verdict,
    /// The status line, what the benchmark actually showed; shown before the numbers.
    pub status: &'static str,
}

impl ExamplePart {
    /// The benchmark case and density this entry runs; `None` only if the table drifted from the
    /// cases, which `tests/demo/parts.rs` refuses.
    pub fn case_and_density(&self) -> Option<(Case, Density)> {
        let case = all_cases().into_iter().find(|c| c.id == self.case_id)?;
        let density = match self.demo_sizing {
            Some(size) => Density {
                label: "demo".to_string(),
                surface_file: self.surface_file.to_string(),
                size,
                series_size: size.at([0.0; 3]),
            },
            None => case
                .densities
                .iter()
                .find(|d| d.surface_file == self.surface_file)?
                .clone(),
        };
        Some((case, density))
    }

    /// The material the benchmark tested with.
    pub fn benchmark_material(&self) -> Material {
        self.case_and_density().map_or(
            Material {
                youngs_modulus: 200_000.0,
                poisson_ratio: 0.3,
            },
            |(case, _)| case.material,
        )
    }
}

